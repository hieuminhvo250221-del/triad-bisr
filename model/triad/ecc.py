"""Hsiao SEC-DED (30, 24) code used by the wrapper, and a generator for its Verilog.

Codeword layout: c[23:0] = data, c[29:24] = check bits.  The 24 data columns of the parity-check
matrix are the 20 six-bit vectors of weight 3 plus 4 of weight 5; the check columns are the unit
vectors.  All columns have odd weight, so every double error has an even-weight (non-zero)
syndrome that matches no column: single errors are corrected, double errors are detected.

    python -m triad.ecc rtl/ecc30_24.v      # regenerate the RTL
"""
from __future__ import annotations

import sys
from itertools import combinations

DATA_BITS = 24
CHECK_BITS = 6
CODE_BITS = DATA_BITS + CHECK_BITS


def _data_columns() -> list[int]:
    cols = [sum(1 << i for i in c) for c in combinations(range(CHECK_BITS), 3)]
    cols += [0b111111 ^ (1 << missing) for missing in range(4)]  # weight 5, balances the row weights
    assert len(cols) == DATA_BITS and len(set(cols)) == DATA_BITS
    return cols


COLUMNS = _data_columns()  # COLUMNS[j] = syndrome of an error in data bit j


def encode(data: int) -> int:
    check = 0
    for j, col in enumerate(COLUMNS):
        if data >> j & 1:
            check ^= col
    return data | check << DATA_BITS


def decode(code: int) -> tuple[int, bool, bool]:
    """Return (data, corrected_error, uncorrectable_error)."""
    data = code & (1 << DATA_BITS) - 1
    syndrome = encode(data) >> DATA_BITS ^ code >> DATA_BITS
    if syndrome == 0:
        return data, False, False
    if syndrome in COLUMNS:
        return data ^ 1 << COLUMNS.index(syndrome), True, False
    if syndrome.bit_count() == 1:  # a check bit is wrong, the data is intact
        return data, True, False
    return data, False, True


def verilog() -> str:
    rows = [[j for j, col in enumerate(COLUMNS) if col >> i & 1] for i in range(CHECK_BITS)]
    out = ["`timescale 1ns/1ps",
           "// Generated by model/triad/ecc.py -- do not edit.  Hsiao SEC-DED (30, 24).",
           "// Codeword: c[23:0] data, c[29:24] check bits.", "",
           "module ecc30_24_enc (", "    input  wire [23:0] d,", "    output wire [29:0] c", ");",
           "    assign c[23:0] = d;"]
    for i, taps in enumerate(rows):
        out.append(f"    assign c[{DATA_BITS + i}] = " + " ^ ".join(f"d[{j}]" for j in taps) + ";")
    out += ["endmodule", "",
            "module ecc30_24_dec (", "    input  wire [29:0] c,", "    output wire [23:0] d,",
            "    output wire        ce,   // single error corrected",
            "    output wire        ue    // uncorrectable (double) error detected", ");",
            "    wire [5:0] s;"]
    for i, taps in enumerate(rows):
        out.append(f"    assign s[{i}] = c[{DATA_BITS + i}] ^ " + " ^ ".join(f"c[{j}]" for j in taps) + ";")
    out.append("    wire [23:0] flip;")
    for j, col in enumerate(COLUMNS):
        out.append(f"    assign flip[{j}] = (s == 6'b{col:06b});")
    out += ["    wire check_err = (s == 6'b000001) | (s == 6'b000010) | (s == 6'b000100) |",
            "                     (s == 6'b001000) | (s == 6'b010000) | (s == 6'b100000);",
            "    assign d  = c[23:0] ^ flip;",
            "    assign ce = (|flip) | check_err;",
            "    assign ue = (|s) & ~ce;",
            "endmodule", ""]
    return "\n".join(out)


if __name__ == "__main__":
    with open(sys.argv[1], "w", newline="\n") as fh:
        fh.write(verilog())
